function loadSource(relative, dependencies = {}) {
  const source = fs.readFileSync(path.resolve(__dirname, "../src/public", relative), "utf8");
  const module = { exports: {} };
  vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, { exports: module.exports, module, require: id => dependencies[id] || {} });
  return module.exports;
}
